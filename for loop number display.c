//Description:program to display numbers 100-50 in descending order(for loop)


#include <stdio.h>

int main() {
    // Loop starts at 100 and decreases down to 50
    for (int i = 100; i >= 50; i--) {
        printf("%d\n", i);
    }
    return 0;
}
